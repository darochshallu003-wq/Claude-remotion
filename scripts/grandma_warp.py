"""Time-warp tables: each version's picture is the original (Indian town, "Grandma") timeline re-timed to its own voice.

Words are aligned sentence by sentence (difflib on the word text, plus hand-picked pairs where the scripts differ);
every aligned word onset becomes an anchor (new frame -> original frame). Writes src/videos/grandma/warps.ts.
Usage: python3 scripts/grandma_warp.py
"""
import difflib, json, pathlib, re, importlib.util

ROOT = pathlib.Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("gv", ROOT / "scripts" / "grandma_voice.py")
src = (ROOT / "scripts" / "grandma_voice.py").read_text()
ns = {}
exec(src[src.index("VO = ["):src.index("# versions:")], ns)  # just the line lists
FPS = 30
tok = lambda line: re.findall(r"[A-Za-z0-9']+", line)

# extra (original word, new word) pairs per sentence where the texts differ: the n-th occurrence is used in order
EXTRA = {
    "grandma_en": {
        2: [("Surveys", "In"), ("eighty", "half"), ("cash", "cash"), ("The", "The")],
        3: [("note", "tenner")],
        5: [("shirt", "coat")],
        10: [("hidden", "hidden"), ("five", "twenty"), ("one", "penny"), ("lunch", "sandwich")],
        11: [("Why", "Why"), ("one", "penny"), ("In", "There's"), ("gifts", "Never"), ("zero", "empty")],
        12: [("A", "A"), ("ending", "inside"), ("one", "keeps"), ("beginning", "coming")],
        13: [("That", "And"), ("loan", "loan")],
        14: [("one", "penny")],
        15: [("rupee", "penny")],
        16: [("one", "fifty"), ("thousand", "fifty"), ("one", "quid")],
    },
    "dadi": {0: [("Grandma", "Dadi")], 4: [("Grandma", "Dadi")]},
}


def sentences(lines, words):
    out, i = [], 0
    for line in lines:
        n = len(tok(line))
        out.append(words[i:i + n]); i += n
    assert i == len(words), (i, len(words))
    return out


def main():
    orig_lines = ns["VO"]
    orig = sentences(orig_lines, json.loads((ROOT / "public" / "grandma" / "words.json").read_text()))
    o_end = orig[-1][-1]["e"]
    res = {}
    for v, key in [("dadi", "VO_DADI"), ("grandma_en", "VO_EN")]:
        new = sentences(ns[key], json.loads((ROOT / "public" / v / "words.json").read_text()))
        pairs = []
        for k, (so, sn) in enumerate(zip(orig, new)):
            a = [w["w"].lower() for w in so]; b = [w["w"].lower() for w in sn]
            for blk in difflib.SequenceMatcher(None, a, b, autojunk=False).get_matching_blocks():
                for j in range(blk.size):
                    pairs.append((so[blk.a + j]["s"], sn[blk.b + j]["s"]))
            used_o, used_n = {}, {}
            for wo, wn in EXTRA.get(v, {}).get(k, []):
                io = [i for i, w in enumerate(so) if w["w"] == wo]; inn = [i for i, w in enumerate(sn) if w["w"] == wn]
                co, cn = used_o.get(wo, 0), used_n.get(wn, 0)
                if co < len(io) and cn < len(inn):
                    pairs.append((so[io[co]]["s"], sn[inn[cn]]["s"]))
                used_o[wo] = co + 1; used_n[wn] = cn + 1
            pairs += [(so[0]["s"], sn[0]["s"]), (so[-1]["e"], sn[-1]["e"])]
        pairs.append((0.0, 0.0))
        n_end = new[-1][-1]["e"]
        pairs.append((o_end + 1.0, n_end + 1.0))
        # keep a strictly increasing monotone chain (drop pairs that would run backwards)
        pairs = sorted(set(pairs), key=lambda p: (p[1], p[0]))
        chain = []
        for po, pn in pairs:
            if chain and (pn <= chain[-1][1] + 1e-3 or po <= chain[-1][0] + 1e-3):
                continue
            chain.append((po, pn))
        total = int(round((n_end + 1.0) * FPS))
        res[v] = {"total": total, "nf": [round(p[1] * FPS, 2) for p in chain], "of": [round(p[0] * FPS, 2) for p in chain]}
        print(v, "anchors", len(chain), "total frames", total)
    out = "// generated by scripts/grandma_warp.py: new frame -> original frame anchors per version (piecewise linear)\n"
    out += "export const WARPS: Record<string, { total: number; nf: number[]; of: number[] }> = " + json.dumps(res) + ";\n"
    (ROOT / "src" / "videos" / "grandma" / "warps.ts").write_text(out)


main()
