"""Voice a multi-character story with Microsoft's Hindi neural voices.

Reads every line from src/<project>/script.ts ({ id, who, text }) and writes
public/<project>/vo/<line id>.mp3 with edge-tts (needs the host
speech.platform.bing.com). Each speaker gets its own voice, rate and pitch;
the witch is pitched down and given an echo. Writes the clip lengths to
src/<project>/timing.ts so the scenes fit the voices.

Usage: python3 scripts/story_tts.py <project>
  e.g.  python3 scripts/story_tts.py ultepair
"""

import asyncio
import os
import pathlib
import re
import subprocess
import sys

import edge_tts

ROOT = pathlib.Path(__file__).resolve().parent.parent

# speaker -> (voice, rate, pitch, extra ffmpeg filter)
VOICES = {
    "N": ("hi-IN-MadhurNeural", "-4%", "-6Hz", "volume=1.1"),  # narrator, slow storyteller
    "B": ("hi-IN-MadhurNeural", "+14%", "+14Hz", "volume=1.1"),  # Bhola, nervous milkman
    "D": ("hi-IN-SwaraNeural", "-2%", "-14Hz", "volume=1.1"),  # Dadi
    # Kamla the witch: slow, low, with a hollow echo
    "W": ("hi-IN-SwaraNeural", "-18%", "-32Hz", "aecho=0.8:0.7:90|180:0.35|0.2,volume=1.3"),
}


def duration(path: pathlib.Path) -> float:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)],
        capture_output=True, text=True, check=True,
    )
    return float(out.stdout.strip())


async def main() -> None:
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    project = sys.argv[1]
    script = ROOT / "src" / project / "script.ts"
    out = ROOT / "public" / project / "vo"
    out.mkdir(parents=True, exist_ok=True)
    proxy = os.environ.get("HTTPS_PROXY") or os.environ.get("https_proxy")
    lines = re.findall(r'\{ id: "([a-z0-9]+)", who: "([NBDW])", text: "(.*?)" \}', script.read_text())
    if not lines:
        raise SystemExit("no lines found in " + str(script))
    timing = {}
    for line_id, who, text in lines:
        voice, rate, pitch, fx = VOICES[who]
        raw = out / f"{line_id}.raw.mp3"
        await edge_tts.Communicate(text, voice, rate=rate, pitch=pitch, proxy=proxy).save(str(raw))
        clip = out / f"{line_id}.mp3"
        subprocess.run(
            [
                "ffmpeg", "-v", "error", "-y", "-i", str(raw), "-af",
                "silenceremove=start_periods=1:start_threshold=-45dB,"
                "areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,"
                # shorten the voice's long sentence pauses
                "silenceremove=stop_periods=-1:stop_threshold=-45dB:stop_duration=0.35:stop_silence=0.35,"
                + fx,
                "-ar", "44100", "-c:a", "libmp3lame", "-q:a", "2", str(clip),
            ],
            check=True,
        )
        raw.unlink()
        timing[line_id] = round(duration(clip), 3)
        print(f"{line_id} {who} {timing[line_id]:5.2f}s")
    body = "\n".join(f'  {k}: {v},' for k, v in timing.items())
    (ROOT / "src" / project / "timing.ts").write_text(
        "// Generated by scripts/story_tts.py: voice clip length in seconds per line.\n"
        f"export const CLIP_SECONDS: Record<string, number> = {{\n{body}\n}};\n"
    )
    print(f"total voice {sum(timing.values()):.1f}s")


if __name__ == "__main__":
    asyncio.run(main())
